package org.example.synchro;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.example.synchro.repositories.AlbumRepository;
import org.example.synchro.repositories.ArtistaRepository;
import org.example.synchro.repositories.MusicaRepository;
import org.example.synchro.services.LastFmCatalogStore;
import org.junit.jupiter.api.Test;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.boot.persistence.autoconfigure.EntityScan;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Import;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.DriverManager;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class CatalogTextSchemaTests {
    @TestConfiguration
    @EnableAutoConfiguration
    @EntityScan("org.example.synchro.entities")
    @EnableJpaRepositories("org.example.synchro.repositories")
    @Import(LastFmCatalogStore.class)
    static class Config {}

    @Test
    void startupWidensLegacyTextColumnsAndPreservesCatalogData() throws Exception {
        String url = "jdbc:h2:mem:legacy-catalog-text";
        try (var connection = DriverManager.getConnection(url, "sa", "")) {
            // Keep the legacy database open while Hibernate upgrades it on startup.
            var sql = connection.createStatement();
            sql.execute("create table midia (id bigint generated by default as identity primary key, "
                    + "titulo varchar(255), descricao varchar(255), lastfm_raw_json varchar(255), lastfm_tags_json varchar(255))");
            sql.execute("create table album (id bigint primary key, titulo_key varchar(255), data_lancamento date)");
            sql.execute("create table artista (id bigint generated by default as identity primary key, "
                    + "nome varchar(255), nome_key varchar(255), biografia varchar(255), "
                    + "lastfm_raw_json varchar(255), lastfm_tags_json varchar(255))");
            sql.execute("insert into midia (id,titulo,descricao,lastfm_raw_json,lastfm_tags_json) "
                    + "values (11,'Good Girl Gone Bad: Reloaded','Descrição existente','{\"saved\":true}','[]')");
            sql.execute("insert into album (id,titulo_key) values (11,'good girl gone bad: reloaded')");
            sql.execute("insert into artista (id,nome,nome_key,biografia) values (21,'Rihanna','rihanna','Biografia existente')");

            try (var app = new SpringApplicationBuilder(Config.class).web(WebApplicationType.NONE).run(
                    "--spring.profiles.active=lastfm-import", "--spring.datasource.url=" + url,
                    "--spring.jpa.hibernate.ddl-auto=update", "--lastfm.api-key=")) {
                var jdbc = app.getBean(JdbcTemplate.class);
                assertEquals("Descrição existente", jdbc.queryForObject("select descricao from midia where id=11", String.class));
                assertEquals("Biografia existente", jdbc.queryForObject("select biografia from artista where id=21", String.class));
                assertEquals("{\"saved\":true}", jdbc.queryForObject("select lastfm_raw_json from midia where id=11", String.class));
                for (String[] column : List.of(new String[]{"MIDIA", "DESCRICAO"}, new String[]{"ARTISTA", "BIOGRAFIA"},
                        new String[]{"MIDIA", "LASTFM_RAW_JSON"}, new String[]{"MIDIA", "LASTFM_TAGS_JSON"},
                        new String[]{"ARTISTA", "LASTFM_RAW_JSON"}, new String[]{"ARTISTA", "LASTFM_TAGS_JSON"})) {
                    long length = jdbc.queryForObject("select character_maximum_length from information_schema.columns "
                            + "where table_name=? and column_name=?", Long.class, column[0], column[1]);
                    assertTrue(length > 100_000, column[0] + "." + column[1] + " must accept complete Last.fm text");
                }

                var json = new ObjectMapper();
                var store = app.getBean(LastFmCatalogStore.class);
                String description = "Descrição completa de Good Girl Gone Bad: Reloaded. ".repeat(30);
                String biography = "Biografia completa de Rihanna, sem truncar o conteúdo. ".repeat(100);
                var tags = List.of(Map.of("name", "tag longa ".repeat(40)));
                long albumId = store.save("album", json.valueToTree(Map.of("name", "Good Girl Gone Bad: Reloaded", "artist", "Rihanna",
                        "wiki", Map.of("content", description), "tags", Map.of("tag", tags))), true);
                assertEquals(11L, albumId, "Enrichment must keep the existing album ID");
                var album = app.getBean(AlbumRepository.class).findById(albumId).orElseThrow();
                assertEquals(description.strip(), album.getDescricao());
                assertEquals(tags, json.readValue(album.getLastFm().getTagsJson(), List.class));
                assertEquals(description.strip(), json.readTree(album.getLastFm().getRawJson()).path("wiki").path("content").asText().strip());

                long artistId = store.save("artist", json.valueToTree(Map.of("name", "Rihanna", "bio", Map.of("content", biography),
                        "tags", Map.of("tag", tags))), true);
                assertEquals(21L, artistId);
                var artist = app.getBean(ArtistaRepository.class).findById(artistId).orElseThrow();
                assertEquals(biography.strip(), artist.getBiografia());
                assertEquals(tags, json.readValue(artist.getLastFm().getTagsJson(), List.class));

                long trackId = store.save("track", json.valueToTree(Map.of("name", "Test track", "artist", "Rihanna",
                        "wiki", Map.of("content", biography))), true);
                assertEquals(biography.strip(), app.getBean(MusicaRepository.class).findById(trackId).orElseThrow().getDescricao());
                assertEquals(1, app.getBean(AlbumRepository.class).count(), "Schema upgrade must preserve existing rows");
            }
        }
    }
}
